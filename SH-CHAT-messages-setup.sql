-- SH-CHAT message media + realtime notifications
-- Run once in Supabase Dashboard > SQL Editor.

-- 1) Message attachments
ALTER TABLE public.messages
  ADD COLUMN IF NOT EXISTS media_url text,
  ADD COLUMN IF NOT EXISTS media_type text;
ALTER TABLE public.messages DROP CONSTRAINT IF EXISTS messages_media_type_check;
ALTER TABLE public.messages ADD CONSTRAINT messages_media_type_check
  CHECK (media_type IS NULL OR media_type IN ('image', 'video'));

-- 2) Storage bucket for images/videos. This bucket is public so message media URLs can be displayed.
-- If you already use post-images, this updates its size/type settings rather than creating a second bucket.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('post-images', 'post-images', true, 52428800,
        ARRAY['image/jpeg','image/png','image/webp','image/gif','image/avif','video/mp4','video/webm','video/ogg'])
ON CONFLICT (id) DO UPDATE SET
  public = EXCLUDED.public,
  file_size_limit = GREATEST(COALESCE(storage.buckets.file_size_limit, 0), EXCLUDED.file_size_limit),
  allowed_mime_types = EXCLUDED.allowed_mime_types;

-- Upload only into the signed-in user's own folder: <auth.uid()>/messages/<filename>
DROP POLICY IF EXISTS "SHCHAT users upload own media" ON storage.objects;
CREATE POLICY "SHCHAT users upload own media" ON storage.objects
FOR INSERT TO authenticated
WITH CHECK (bucket_id = 'post-images' AND (storage.foldername(name))[1] = auth.uid()::text);
DROP POLICY IF EXISTS "SHCHAT users update own media" ON storage.objects;
CREATE POLICY "SHCHAT users update own media" ON storage.objects
FOR UPDATE TO authenticated
USING (bucket_id = 'post-images' AND (storage.foldername(name))[1] = auth.uid()::text)
WITH CHECK (bucket_id = 'post-images' AND (storage.foldername(name))[1] = auth.uid()::text);
DROP POLICY IF EXISTS "SHCHAT users delete own media" ON storage.objects;
CREATE POLICY "SHCHAT users delete own media" ON storage.objects
FOR DELETE TO authenticated
USING (bucket_id = 'post-images' AND (storage.foldername(name))[1] = auth.uid()::text);

-- 3) Enable realtime for new messages. Ignore duplicate membership if already enabled.
DO $$ BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
EXCEPTION WHEN duplicate_object THEN NULL;
WHEN undefined_object THEN NULL;
END $$;

-- 4) Persistent notifications for incoming messages.
CREATE TABLE IF NOT EXISTS public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  type text NOT NULL CHECK (type IN ('message', 'friend_request', 'friend_accepted')),
  entity_id text,
  message text NOT NULL DEFAULT 'لديك إشعار جديد',
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS notifications_recipient_created_idx
  ON public.notifications (recipient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS notifications_recipient_unread_idx
  ON public.notifications (recipient_id, is_read) WHERE is_read = false;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users read own notifications" ON public.notifications;
CREATE POLICY "Users read own notifications" ON public.notifications
FOR SELECT TO authenticated USING (recipient_id = auth.uid());
DROP POLICY IF EXISTS "Users update own notifications" ON public.notifications;
CREATE POLICY "Users update own notifications" ON public.notifications
FOR UPDATE TO authenticated USING (recipient_id = auth.uid()) WITH CHECK (recipient_id = auth.uid());

CREATE OR REPLACE FUNCTION public.shchat_notify_new_message()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE sender_name text;
BEGIN
  IF NEW.sender_id IS NULL OR NEW.receiver_id IS NULL OR NEW.sender_id = NEW.receiver_id THEN
    RETURN NEW;
  END IF;
  SELECT COALESCE(NULLIF(full_name, ''), NULLIF(username, ''), 'عضو SH-CHAT')
    INTO sender_name FROM public.profiles WHERE id = NEW.sender_id;
  INSERT INTO public.notifications(recipient_id, actor_id, type, entity_id, message)
  VALUES (NEW.receiver_id, NEW.sender_id, 'message', NEW.id::text,
          COALESCE(sender_name, 'عضو SH-CHAT') || ' أرسل إليك رسالة جديدة.');
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS shchat_message_notification ON public.messages;
CREATE TRIGGER shchat_message_notification AFTER INSERT ON public.messages
FOR EACH ROW EXECUTE FUNCTION public.shchat_notify_new_message();

DO $$ BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE public.notifications;
EXCEPTION WHEN duplicate_object THEN NULL;
WHEN undefined_object THEN NULL;
END $$;
NOTIFY pgrst, 'reload schema';
