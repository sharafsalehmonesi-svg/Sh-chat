-- SH-CHAT database setup for Supabase
-- Run this script in Supabase Dashboard > SQL Editor.
-- Review your existing schema before running in a live project.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  full_name text not null default 'عضو SH-CHAT',
  bio text not null default '',
  avatar_url text,
  cover_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  content text,
  image_url text,
  created_at timestamptz not null default now(),
  constraint posts_content_or_image check (
    (content is not null and length(trim(content)) > 0) or image_url is not null
  )
);

create table if not exists public.likes (
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(post_id,user_id)
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  content text not null check(length(trim(content)) > 0 and length(content) <= 1000),
  created_at timestamptz not null default now()
);

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  addressee_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check(status in ('pending','accepted','rejected')),
  created_at timestamptz not null default now(),
  constraint friendship_not_self check(requester_id <> addressee_id),
  constraint friendship_pair_unique unique(requester_id,addressee_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  receiver_id uuid not null references auth.users(id) on delete cascade,
  content text not null check(length(trim(content)) > 0 and length(content) <= 4000),
  created_at timestamptz not null default now(),
  constraint message_not_self check(sender_id <> receiver_id)
);

create index if not exists posts_created_at_idx on public.posts(created_at desc);
create index if not exists posts_user_id_idx on public.posts(user_id);
create index if not exists comments_post_id_idx on public.comments(post_id,created_at);
create index if not exists messages_pair_time_idx on public.messages(sender_id,receiver_id,created_at);
create index if not exists friendships_addressee_status_idx on public.friendships(addressee_id,status);

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.likes enable row level security;
alter table public.comments enable row level security;
alter table public.friendships enable row level security;
alter table public.messages enable row level security;

-- Profiles: publicly readable, owner-editable
drop policy if exists "Profiles are public" on public.profiles;
create policy "Profiles are public" on public.profiles for select using (true);
drop policy if exists "Users insert own profile" on public.profiles;
create policy "Users insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

-- Posts: public read, author create/delete
drop policy if exists "Posts are public" on public.posts;
create policy "Posts are public" on public.posts for select using (true);
drop policy if exists "Users create own posts" on public.posts;
create policy "Users create own posts" on public.posts for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users delete own posts" on public.posts;
create policy "Users delete own posts" on public.posts for delete to authenticated using (auth.uid() = user_id);

-- Likes: public read, user can manage own likes
drop policy if exists "Likes are public" on public.likes;
create policy "Likes are public" on public.likes for select using (true);
drop policy if exists "Users add own likes" on public.likes;
create policy "Users add own likes" on public.likes for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users remove own likes" on public.likes;
create policy "Users remove own likes" on public.likes for delete to authenticated using (auth.uid() = user_id);

-- Comments: public read, author create/delete
drop policy if exists "Comments are public" on public.comments;
create policy "Comments are public" on public.comments for select using (true);
drop policy if exists "Users add own comments" on public.comments;
create policy "Users add own comments" on public.comments for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users delete own comments" on public.comments;
create policy "Users delete own comments" on public.comments for delete to authenticated using (auth.uid() = user_id);

-- Friendships: only participants can view/manage their requests
drop policy if exists "Participants view friendships" on public.friendships;
create policy "Participants view friendships" on public.friendships for select to authenticated using (auth.uid() = requester_id or auth.uid() = addressee_id);
drop policy if exists "Users send friend requests" on public.friendships;
create policy "Users send friend requests" on public.friendships for insert to authenticated with check (auth.uid() = requester_id and status = 'pending');
drop policy if exists "Addressee updates friend request" on public.friendships;
create policy "Addressee updates friend request" on public.friendships for update to authenticated using (auth.uid() = addressee_id) with check (auth.uid() = addressee_id and status in ('accepted','rejected'));
drop policy if exists "Participants delete friendship" on public.friendships;
create policy "Participants delete friendship" on public.friendships for delete to authenticated using (auth.uid() = requester_id or auth.uid() = addressee_id);

-- Messages: only sender/receiver may read; sender can send to accepted friend
drop policy if exists "Participants read messages" on public.messages;
create policy "Participants read messages" on public.messages for select to authenticated using (auth.uid() = sender_id or auth.uid() = receiver_id);
drop policy if exists "Send messages to friends" on public.messages;
create policy "Send messages to friends" on public.messages for insert to authenticated with check (
  auth.uid() = sender_id and exists (
    select 1 from public.friendships f
    where f.status = 'accepted'
      and ((f.requester_id = auth.uid() and f.addressee_id = receiver_id)
        or (f.addressee_id = auth.uid() and f.requester_id = receiver_id))
  )
);

-- Storage bucket for public post/profile images.
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('post-images','post-images',true,5242880,array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public = true, file_size_limit = 5242880;

drop policy if exists "Public can view SH chat images" on storage.objects;
create policy "Public can view SH chat images" on storage.objects for select using (bucket_id = 'post-images');
drop policy if exists "Authenticated users upload own SH chat images" on storage.objects;
create policy "Authenticated users upload own SH chat images" on storage.objects for insert to authenticated with check (
  bucket_id = 'post-images' and (storage.foldername(name))[1] = auth.uid()::text
);
drop policy if exists "Users delete own SH chat images" on storage.objects;
create policy "Users delete own SH chat images" on storage.objects for delete to authenticated using (
  bucket_id = 'post-images' and (storage.foldername(name))[1] = auth.uid()::text
);

-- Enable realtime for chat messages (ignore if already added).
do $$
begin
  alter publication supabase_realtime add table public.messages;
exception when duplicate_object then null;
when undefined_object then raise notice 'Publication supabase_realtime not found; enable Realtime for messages in Dashboard.';
end $$;

